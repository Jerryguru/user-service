package com.userservice.enums;

/**
 * ==========================================================
 * Enum Name : UserStatus
 *
 * Description:
 * Represents the current status of the User.
 * ==========================================================
 */
public enum UserStatus {

    /**
     * User account is active.
     */
    ACTIVE,

    /**
     * User account is inactive.
     */
    INACTIVE,

    /**
     * User account is blocked.
     */
    BLOCKED

}