package com.userservice.entity;

/**
 * Represents the gender of a user.
 *
 * Enum is used because the application
 * supports a fixed set of gender values.
 */
public enum Gender {

    /**
     * Male user.
     */
    MALE,

    /**
     * Female user.
     */
    FEMALE,

    /**
     * Other gender.
     */
    OTHER
}